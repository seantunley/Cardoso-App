// Dumps the current schema (as it would exist after running every
// migration in src/db/migrations.js) to docs/schema.sql.
//
// Why: with 80+ migrations, nobody can read migrations.js and answer
// "what does the database look like today?" without walking the
// history. This script gives us a single human-readable mirror that
// updates on every commit — PRs that change schema show a diff in
// schema.sql which makes review obvious.
//
// Strategy:
//   1. Create an in-memory SQLite DB (no need to touch the real DB).
//   2. Run runMigrations against it.
//   3. SELECT every CREATE statement from sqlite_master, sorted in a
//      stable order (tables first, then indexes, then views/triggers),
//      grouped by table for readability.
//   4. Write to docs/schema.sql with a header noting it's generated.
//
// Run manually:
//   node scripts/dump-schema-snapshot.mjs
//
// Or wire into CI to fail when the committed schema.sql is stale.

import { writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, resolve } from "node:path";
import Database from "better-sqlite3";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, "..");
const migrationsPath = pathToFileURL(resolve(repoRoot, "src/db/migrations.js")).href;
const schemaPath     = pathToFileURL(resolve(repoRoot, "src/db/schema.js")).href;
const batSchemaPath  = pathToFileURL(resolve(repoRoot, "src/db/batSchema.js")).href;
const outPath = resolve(repoRoot, "docs/schema.sql");

// In-memory DB — no filesystem trace, no cross-contamination with the
// real database file.
const db = new Database(":memory:");

// initSchema internally invokes runMigrations once the base tables
// are in place. Several migrations (v45+) depend on tables created by
// initBatSchema, so the bat schema has to land first or the
// migrations fail with "no such table: bat_cardoso_invoices".
const { initBatSchema } = await import(batSchemaPath);
initBatSchema(db);
const { initSchema } = await import(schemaPath);
initSchema(db);

// Read every object out of sqlite_master and group by table. The
// `sql` column is null for the auto-generated indexes that back
// PRIMARY KEY / UNIQUE — skip those (filter on sql IS NOT NULL).
const objects = db.prepare(`
  SELECT type, name, tbl_name, sql
  FROM sqlite_master
  WHERE sql IS NOT NULL
    AND name NOT LIKE 'sqlite_%'
  ORDER BY
    CASE type
      WHEN 'table'   THEN 1
      WHEN 'view'    THEN 2
      WHEN 'index'   THEN 3
      WHEN 'trigger' THEN 4
      ELSE 5
    END,
    tbl_name COLLATE NOCASE,
    name COLLATE NOCASE
`).all();

const tables = objects.filter((o) => o.type === "table");
const views    = objects.filter((o) => o.type === "view");
const indexes  = objects.filter((o) => o.type === "index");
const triggers = objects.filter((o) => o.type === "trigger");

const lastMigration = db.prepare(`
  SELECT MAX(version) AS v FROM schema_migrations
`).get();

const lines = [];
lines.push("-- AUTOGENERATED by scripts/dump-schema-snapshot.mjs.");
lines.push("-- Do not edit by hand — re-run the script after a schema change.");
lines.push(`-- Source of truth: src/db/migrations.js (latest version: ${lastMigration?.v ?? "n/a"})`);
lines.push(`-- Generated: ${new Date().toISOString()}`);
lines.push("");

const indexesByTable = indexes.reduce((acc, idx) => {
  (acc[idx.tbl_name] ||= []).push(idx);
  return acc;
}, {});

const triggersByTable = triggers.reduce((acc, t) => {
  (acc[t.tbl_name] ||= []).push(t);
  return acc;
}, {});

for (const t of tables) {
  lines.push(`-- ── ${t.name} ──`);
  lines.push(t.sql.trim() + ";");
  for (const idx of indexesByTable[t.name] || []) {
    lines.push(idx.sql.trim() + ";");
  }
  for (const trg of triggersByTable[t.name] || []) {
    lines.push(trg.sql.trim() + ";");
  }
  lines.push("");
}

if (views.length) {
  lines.push("-- ── views ──");
  for (const v of views) {
    lines.push(v.sql.trim() + ";");
  }
  lines.push("");
}

writeFileSync(outPath, lines.join("\n"));
console.log(`Wrote ${outPath} — ${tables.length} tables, ${indexes.length} indexes, ${triggers.length} triggers, ${views.length} views`);
